def _normalize_name_text(text: str) -> str:
    """Match the historical diary name normalizer without DOCX dependencies."""
    value = text or ""
    value = re.sub(r"[\u00ad\u200b\u200c\u200d\u2060\ufeff]", "", value)
    value = value.replace("\xa0", " ").replace("\n", " ")
    value = re.sub(r"[ \t\r\f\v]+", " ", value).strip()
    return value


