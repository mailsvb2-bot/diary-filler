from __future__ import annotations

from pathlib import Path
from tempfile import TemporaryDirectory

from docx import Document

from medical_parser import MedicalTextParser


def _assert_fields(parsed, *, tag: str) -> None:
    expected = {
        "complaints": "Тревога и нарушение сна.",
        "life_anamnesis": "Родился в Нижнем Новгороде, развивался соответственно возрасту.",
        "disease_anamnesis": (
            "Болен около двух лет. Лечение ранее проводилось амбулаторно; "
            "это часть анамнеза и не новый раздел. Диагноз ранее уточнялся; "
            "это тоже часть анамнеза."
        ),
        "mental_status": (
            "Ориентирован, контактен. Психический статус в динамике менялся постепенно; "
            "это описание внутри статуса."
        ),
        "somatic_status": "Состояние удовлетворительное, гемодинамика стабильна.",
        "treatment_plan": "Рисперидон 2 мг вечером.",
        "diagnosis": "F20.0 Параноидная шизофрения",
    }
    for field_name, wanted in expected.items():
        got = getattr(parsed, field_name)
        assert got == wanted, f"{tag}: {field_name}: expected {wanted!r}, got {got!r}"


def _docx_one_paragraph(tmp: Path, body: str, name: str) -> Path:
    path = tmp / name
    doc = Document()
    doc.add_paragraph(body)
    doc.save(path)
    return path


def assert_colon_one_paragraph() -> None:
    text = (
        "10.06.2026 Первичный осмотр. "
        "Ф.И.О.: Маркер Однострочный Тестовый. Дата рождения: 01.01.1980. "
        "Жалобы: Тревога и нарушение сна. "
        "Анамнез жизни: Родился в Нижнем Новгороде, развивался соответственно возрасту. "
        "Анамнез заболевания: Болен около двух лет. Лечение ранее проводилось амбулаторно; "
        "это часть анамнеза и не новый раздел. Диагноз ранее уточнялся; это тоже часть анамнеза. "
        "Психический статус: Ориентирован, контактен. Психический статус в динамике менялся постепенно; "
        "это описание внутри статуса. "
        "Соматический статус: Состояние удовлетворительное, гемодинамика стабильна. "
        "План лечения: Рисперидон 2 мг вечером. Диагноз: F20.0 Параноидная шизофрения"
    )
    _assert_fields(MedicalTextParser().parse_text(text), tag="colon")


