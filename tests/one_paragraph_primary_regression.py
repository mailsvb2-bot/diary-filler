def assert_real_docx_single_paragraph() -> None:
    with TemporaryDirectory(prefix="medical-autofill-one-paragraph-") as temp_dir:
        root = Path(temp_dir)
        text = (
            "10.06.2026 Первичный осмотр. "
            "Ф.И.О.: Маркер Однострочный Тестовый. Дата рождения: 01.01.1980. "
            "Жалобы Тревога и нарушение сна. "
            "Анамнез жизни Родился в Нижнем Новгороде, развивался соответственно возрасту. "
            "Анамнез заболевания Болен около двух лет. Лечение ранее проводилось амбулаторно; "
            "это часть анамнеза и не новый раздел. Диагноз ранее уточнялся; это тоже часть анамнеза. "
            "Психический статус Ориентирован, контактен. Психический статус в динамике менялся постепенно; "
            "это описание внутри статуса. "
            "Соматический статус Состояние удовлетворительное, гемодинамика стабильна. "
            "План лечения Рисперидон 2 мг вечером. Диагноз F20.0 Параноидная шизофрения"
        )
        source = _docx_one_paragraph(root, text, "one-paragraph-primary.docx")
        parsed = MedicalTextParser().parse_docx(source)
        _assert_fields(parsed, tag="docx")


def main() -> None:
    assert_colon_one_paragraph()
    assert_dash_and_dot_labels_one_paragraph()
    assert_separatorless_headings_after_sentence_boundaries()
    assert_real_docx_single_paragraph()
    print(
        "ONE-PARAGRAPH PRIMARY REGRESSION OK: colon/dash/dot/separatorless sections "
        "parse without truncating narrative treatment/diagnosis/status phrases"
    )


if __name__ == "__main__":
    main()
